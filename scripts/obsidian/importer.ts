// Obsidian → Astro importer. Two phases:
//
//   planImport()  reads the vault and the site, validates everything, and
//                 returns a plan. It never writes. (`npm run import:check`)
//   applyPlan()   writes exactly what the plan says. It refuses if the plan has
//                 errors, and deletes articles only when pruning is confirmed.
//
// Safety rules:
//   - Only <vault>/articles/** is read. Symlinks anywhere inside it are
//     rejected, and every resolved file must stay inside it.
//   - A note is imported only with `publish: true` AND `draft: false`.
//   - Only folders this importer created (frontmatter `importedFrom`) are ever
//     written or deleted. Manually maintained articles are never touched.
//   - Output is deterministic, and unchanged files aren't rewritten.
import { lstatSync, readFileSync, realpathSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile, lstat, realpath } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { z } from "astro/zod";
import { CATEGORY_SLUGS } from "../../src/config/categories.ts";
import {
  DATE_PATTERN,
  DESCRIPTION_MAX,
  PATH_PATTERN,
  RESERVED_SLUGS,
  SLUG_PATTERN,
  TAG_PATTERN,
  TITLE_MAX,
} from "../../src/config/content-rules.ts";
import { FrontmatterError, parseNote, serializeFrontmatter, type Value } from "./frontmatter.ts";
import { collectAnchors, transformBody, type NoteRef, type Resolution } from "./markdown.ts";

export interface ImportOptions {
  /** The Obsidian vault root. Only `<vault>/articles/` is read. */
  vaultDir: string;
  /** The site's article collection, e.g. `src/content/blog`. */
  contentDir: string;
}

export interface PlannedArticle {
  slug: string;
  source: string; // vault-relative, e.g. articles/linux/Foo.md
  status: "create" | "update" | "unchanged";
  /** File name → content, for everything in the article folder. */
  files: Map<string, Buffer>;
  /** For updates: files that change, and stale files to remove. */
  changed: string[];
  removed: string[];
  renamedFrom?: string;
}

export interface StaleArticle {
  slug: string;
  source: string;
}

export interface ImportPlan {
  vaultDir: string;
  contentDir: string;
  articles: PlannedArticle[];
  skippedDrafts: string[];
  unmarkedCount: number;
  stale: StaleArticle[];
  errors: string[];
  warnings: string[];
}

export interface ApplyResult {
  written: string[];
  pruned: string[];
}

const GENERATED_HEADER = [
  "Generated by `npm run import` from the Obsidian vault.",
  "Edit the vault note, not this file: the next import overwrites it.",
];
const OBSIDIAN_ONLY = ["aliases", "cssclasses", "cssclass"];
const ALLOWED_KEYS = [
  "publish",
  "draft",
  "slug",
  "title",
  "description",
  "pubDate",
  "updatedDate",
  "category",
  "tags",
  "cover",
  "coverAlt",
  "toc",
  "legacyUrls",
  ...OBSIDIAN_ONLY,
];

const dateString = z
  .string()
  .regex(DATE_PATTERN, "use the YYYY-MM-DD format")
  .refine((value) => !Number.isNaN(Date.parse(`${value}T00:00:00Z`)) && new Date(`${value}T00:00:00Z`).toISOString().startsWith(value), "is not a real calendar date");

const noteSchema = z
  .object({
    publish: z.literal(true),
    draft: z.boolean({ error: "is required: set draft: false to publish (or true to keep the note unpublished)" }),
    slug: z
      .string({ error: "is required: the URL path, e.g. slug: error-budgets" })
      .regex(SLUG_PATTERN, "must be lowercase words joined by hyphens, e.g. error-budgets")
      .refine((slug) => !(RESERVED_SLUGS as readonly string[]).includes(slug), "is reserved by the site's URL structure"),
    title: z.string().trim().min(1).max(TITLE_MAX),
    description: z.string().trim().min(1).max(DESCRIPTION_MAX, `must be ${DESCRIPTION_MAX} characters or fewer`),
    pubDate: dateString,
    updatedDate: dateString.optional(),
    category: z.enum(CATEGORY_SLUGS, { error: `must be one of: ${CATEGORY_SLUGS.join(", ")}` }),
    tags: z
      .array(z.string().regex(TAG_PATTERN, "must be lowercase-hyphenated, without a leading #"))
      .default([])
      .refine((tags) => new Set(tags).size === tags.length, "must not contain duplicates"),
    cover: z.string().trim().min(1).optional(),
    coverAlt: z.string().trim().min(1).optional(),
    toc: z.boolean().optional(),
    legacyUrls: z.array(z.string().regex(PATH_PATTERN, "must be site paths starting with /")).default([]),
    aliases: z.unknown().optional(),
    cssclasses: z.unknown().optional(),
    cssclass: z.unknown().optional(),
  })
  .strict()
  .superRefine((data, ctx) => {
    if (data.cover && !data.coverAlt) ctx.addIssue({ code: "custom", path: ["coverAlt"], message: "is required when cover is set" });
    if (data.updatedDate && data.updatedDate < data.pubDate) ctx.addIssue({ code: "custom", path: ["updatedDate"], message: "can't be earlier than pubDate" });
  });

type NoteData = z.infer<typeof noteSchema>;

interface VaultNote {
  abs: string;
  rel: string; // vault-relative, posix
  folderCategory?: string;
  body: string;
  bodyStartLine: number;
  data?: NoteData;
  state: "candidate" | "draft" | "unmarked" | "invalid";
  anchors: Set<string>;
}

const toPosix = (path: string) => path.split(sep).join("/");
const isInside = (root: string, path: string) => path === root || path.startsWith(root + sep);

async function walk(dir: string, root: string, errors: string[]): Promise<string[]> {
  const files: string[] = [];
  for (const entry of (await readdir(dir, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith(".")) continue;
    const abs = join(dir, entry.name);
    if (entry.isSymbolicLink()) {
      errors.push(`${toPosix(relative(root, abs))}: symlinks aren't allowed inside articles/. Move the real file into the vault.`);
    } else if (entry.isDirectory()) {
      files.push(...(await walk(abs, root, errors)));
    } else if (entry.isFile() && entry.name.toLowerCase().endsWith(".md")) {
      files.push(abs);
    }
  }
  return files;
}

function formatIssues(rel: string, error: z.ZodError): string[] {
  return error.issues.map((issue) => {
    if (issue.code === "unrecognized_keys") {
      return `${rel}: unknown propert${issue.keys.length > 1 ? "ies" : "y"} ${issue.keys.map((k) => `"${k}"`).join(", ")}. Allowed: ${ALLOWED_KEYS.join(", ")}.`;
    }
    return `${rel}: ${issue.path.join(".") || "frontmatter"} ${issue.message}`;
  });
}

async function readVault(articlesRoot: string, vaultRoot: string, errors: string[]): Promise<VaultNote[]> {
  const notes: VaultNote[] = [];
  for (const abs of await walk(articlesRoot, vaultRoot, errors)) {
    const rel = toPosix(relative(vaultRoot, abs));
    const segments = toPosix(relative(articlesRoot, abs)).split("/");
    const folderCategory = segments.length > 1 ? segments[0] : undefined;
    const note: VaultNote = { abs, rel, folderCategory, body: "", bodyStartLine: 1, state: "unmarked", anchors: new Set() };
    notes.push(note);

    let parsed;
    try {
      parsed = parseNote(await readFile(abs, "utf8"));
    } catch (error) {
      if (!(error instanceof FrontmatterError)) throw error;
      errors.push(`${rel}: ${error.message}`);
      note.state = "invalid";
      continue;
    }
    if (!parsed) continue; // no frontmatter: not an article candidate
    note.body = parsed.body;
    note.bodyStartLine = parsed.bodyStartLine;

    const publish = parsed.data.publish;
    if (publish === undefined || publish === null || publish === false) continue;
    if (publish !== true) {
      errors.push(`${rel}: publish must be true or false (found "${String(publish)}").`);
      note.state = "invalid";
      continue;
    }

    // Empty Obsidian properties (`key:`) count as absent.
    const raw: Record<string, Value> = Object.fromEntries(Object.entries(parsed.data).filter(([, v]) => v !== null));
    const result = noteSchema.safeParse(raw);
    if (!result.success) {
      errors.push(...formatIssues(rel, result.error));
      note.state = "invalid";
      continue;
    }
    note.data = result.data;
    if (!folderCategory) {
      errors.push(`${rel}: articles must be inside a category folder, e.g. articles/${result.data.category}/.`);
      note.state = "invalid";
      continue;
    }
    if (folderCategory !== result.data.category) {
      errors.push(`${rel}: category "${result.data.category}" doesn't match its folder "articles/${folderCategory}/". Move the note or fix the category.`);
      note.state = "invalid";
      continue;
    }
    note.state = result.data.draft ? "draft" : "candidate";
    note.anchors = collectAnchors(parsed.body);
  }
  return notes;
}

interface SiteArticle {
  slug: string;
  dir: string;
  managed: boolean;
  importedFrom?: string;
}

async function readSite(contentDir: string): Promise<Map<string, SiteArticle>> {
  const site = new Map<string, SiteArticle>();
  for (const entry of await readdir(contentDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const dir = join(contentDir, entry.name);
    let importedFrom: string | undefined;
    let source: string | undefined;
    for (const name of ["index.md", "index.mdx"]) {
      try {
        source = await readFile(join(dir, name), "utf8");
        break;
      } catch {
        // try the next name
      }
    }
    if (source) {
      const frontmatter = source.replace(/\r\n?/g, "\n").match(/^---\n([\s\S]*?)\n---/);
      const match = frontmatter?.[1].match(/^importedFrom:\s*"?([^"\n]+)"?\s*$/m);
      importedFrom = match?.[1];
    }
    site.set(entry.name, { slug: entry.name, dir, managed: importedFrom !== undefined, importedFrom });
  }
  return site;
}

/** Resolve a file the note references, enforcing: exists, regular file, no symlink, inside articles/. */
function safeFile(candidate: string, articlesRoot: string, label: string): Resolution<string> {
  const abs = resolve(candidate);
  if (!isInside(articlesRoot, abs)) return { ok: false, error: `${label} points outside the vault's articles/ folder.` };
  let info;
  try {
    info = lstatSync(abs);
  } catch {
    return { ok: false, error: `${label} was not found.` };
  }
  if (info.isSymbolicLink()) return { ok: false, error: `${label} is a symlink. Use the real file.` };
  if (!info.isFile()) return { ok: false, error: `${label} is not a file.` };
  if (!isInside(articlesRoot, realpathSync(abs))) return { ok: false, error: `${label} resolves outside the vault's articles/ folder.` };
  return { ok: true, value: abs };
}

function imageResolver(noteAbs: string, articlesRoot: string) {
  const noteDir = dirname(noteAbs);
  return (ref: string, form: "embed" | "path"): Resolution<string> => {
    if (/^https?:\/\//i.test(ref)) return { ok: false, error: `cover "${ref}" must be a file in the vault, not a URL.` };
    const label = `image "${ref}"`;
    if (form === "path") return safeFile(join(noteDir, ref), articlesRoot, label);
    // Embeds: look next to the note, then in its assets/ folder.
    const tries = [join(noteDir, ref), join(noteDir, "assets", ref)];
    for (const path of tries) {
      const found = safeFile(path, articlesRoot, label);
      if (found.ok || !found.error.endsWith("was not found.")) return found;
    }
    return { ok: false, error: `${label} was not found next to the note or in its assets/ folder.` };
  };
}

export async function planImport(options: ImportOptions): Promise<ImportPlan> {
  const errors: string[] = [];
  const warnings: string[] = [];
  const plan: ImportPlan = {
    vaultDir: options.vaultDir,
    contentDir: options.contentDir,
    articles: [],
    skippedDrafts: [],
    unmarkedCount: 0,
    stale: [],
    errors,
    warnings,
  };

  let vaultRoot: string;
  try {
    vaultRoot = await realpath(options.vaultDir);
  } catch {
    errors.push(`Vault not found: ${options.vaultDir}`);
    return plan;
  }
  const articlesPath = join(vaultRoot, "articles");
  try {
    const info = await lstat(articlesPath);
    if (info.isSymbolicLink()) errors.push("articles/ is a symlink. It must be a real folder inside the vault.");
    else if (!info.isDirectory()) errors.push("articles/ is not a folder.");
  } catch {
    errors.push(`No articles/ folder in the vault (${vaultRoot}). Create it and put publishable notes in articles/<category>/.`);
  }
  if (errors.length) return plan;
  const articlesRoot = articlesPath;
  const contentDir = resolve(options.contentDir);

  const notes = await readVault(articlesRoot, vaultRoot, errors);
  const candidates = notes.filter((n) => n.state === "candidate");
  plan.skippedDrafts = notes.filter((n) => n.state === "draft").map((n) => n.rel);
  plan.unmarkedCount = notes.filter((n) => n.state === "unmarked").length;

  // Slug uniqueness among candidates.
  const bySlug = new Map<string, VaultNote>();
  for (const note of candidates) {
    const other = bySlug.get(note.data!.slug);
    if (other) errors.push(`slug "${note.data!.slug}" is used by both ${other.rel} and ${note.rel}.`);
    else bySlug.set(note.data!.slug, note);
  }

  // Link resolution indexes (case-insensitive, like Obsidian).
  const refOf = (note: VaultNote): NoteRef => ({ slug: note.data!.slug, title: note.data!.title, anchors: note.anchors });
  const byName = new Map<string, VaultNote[]>();
  const byPath = new Map<string, VaultNote>();
  for (const note of notes) {
    const name = note.rel.split("/").pop()!.replace(/\.md$/i, "").toLowerCase();
    byName.set(name, [...(byName.get(name) ?? []), note]);
    const inArticles = note.rel.replace(/^articles\//, "").replace(/\.md$/i, "").toLowerCase();
    byPath.set(inArticles, note);
    byPath.set(note.rel.replace(/\.md$/i, "").toLowerCase(), note);
  }
  const notPublished = (note: VaultNote, label: string): Resolution<NoteRef> => ({
    ok: false,
    error:
      note.state === "draft"
        ? `${label} is still a draft (draft: true). Publish it first, or replace the link with plain text.`
        : `${label} isn't published (needs publish: true and draft: false). Publish it, or replace the link with plain text.`,
  });
  const resolveWikilink = (target: string): Resolution<NoteRef> => {
    const key = target.replace(/\.md$/i, "").toLowerCase();
    const label = `[[${target}]]`;
    const direct = key.includes("/") ? byPath.get(key) : undefined;
    const matches = direct ? [direct] : (byName.get(key) ?? []);
    if (matches.length === 0) return { ok: false, error: `no note named "${target}" in articles/. Only published articles can be linked.` };
    if (matches.length > 1) return { ok: false, error: `"${target}" matches ${matches.map((m) => m.rel).join(" and ")}. Use a path, e.g. [[${matches[0].rel.replace(/^articles\//, "").replace(/\.md$/, "")}]].` };
    const note = matches[0];
    return note.state === "candidate" ? { ok: true, value: refOf(note) } : notPublished(note, label);
  };

  // Existing site articles.
  const site = await readSite(contentDir);
  const candidateSources = new Set(candidates.map((n) => n.rel));

  for (const note of candidates) {
    const data = note.data!;
    if (bySlug.get(data.slug) !== note) continue; // duplicate slug, already reported

    const existing = site.get(data.slug);
    let renamedFrom: string | undefined;
    if (existing && !existing.managed) {
      errors.push(`${note.rel}: slug "${data.slug}" belongs to a manually maintained article (src/content/blog/${data.slug}/). The importer never overwrites it. Choose another slug.`);
      continue;
    }
    if (existing?.managed && existing.importedFrom !== note.rel) {
      if (candidateSources.has(existing.importedFrom!)) {
        errors.push(`${note.rel}: slug "${data.slug}" is already imported from ${existing.importedFrom}.`);
        continue;
      }
      renamedFrom = existing.importedFrom; // the note was moved or renamed in the vault
    }

    const noteDir = dirname(note.abs);
    const resolveImage = imageResolver(note.abs, articlesRoot);
    const transformed = transformBody(
      note.body,
      {
        title: data.title,
        selfAnchors: note.anchors,
        resolveWikilink,
        resolveMarkdownLink: (path) => {
          const abs = resolve(noteDir, path);
          if (!isInside(articlesRoot, abs)) return { ok: false, error: "links outside the vault's articles/ folder." };
          const target = notes.find((n) => n.abs === abs);
          if (!target) return { ok: false, error: `no note at ${toPosix(relative(articlesRoot, abs))} in articles/.` };
          return target.state === "candidate" ? { ok: true, value: refOf(target) } : notPublished(target, path);
        },
        resolveImage,
      },
      note.bodyStartLine,
    );
    errors.push(...transformed.errors.map((e) => `${note.rel}: ${e}`));
    warnings.push(...transformed.warnings.map((w) => `${note.rel}: ${w}`));

    // Cover image: "[[cover.png]]" (Obsidian property link) or a relative path.
    let coverName: string | undefined;
    if (data.cover) {
      const link = data.cover.match(/^\[\[([^\]|]+)(?:\|[^\]]*)?\]\]$/);
      const resolved = link ? resolveImage(link[1].trim(), "embed") : resolveImage(data.cover.replace(/^\.\//, ""), "path");
      if (!resolved.ok) {
        errors.push(`${note.rel}: cover ${resolved.error.replace(/^image /, "")}`);
      } else if (!/\.(png|jpe?g|gif|webp|avif)$/i.test(resolved.value)) {
        errors.push(`${note.rel}: cover must be a PNG, JPEG, GIF, WebP, or AVIF image.`);
      } else {
        const base = resolved.value.split(sep).pop()!;
        const ext = base.slice(base.lastIndexOf(".")).toLowerCase();
        coverName = transformed.assets.get(resolved.value) ?? `cover${ext}`;
        if (!transformed.assets.has(resolved.value)) {
          if ([...transformed.assets.values()].includes(coverName)) coverName = `cover-image${ext}`;
          transformed.assets.set(resolved.value, coverName);
        }
      }
    }

    if (transformed.errors.length || errors.some((e) => e.startsWith(`${note.rel}:`))) continue;

    const frontmatter = serializeFrontmatter(
      [
        ["importedFrom", note.rel],
        ["title", data.title],
        ["description", data.description],
        ["pubDate", data.pubDate],
        ["updatedDate", data.updatedDate],
        ["category", data.category],
        ["tags", data.tags.length ? data.tags : undefined],
        ["draft", false],
        ["cover", coverName ? `./${coverName}` : undefined],
        ["coverAlt", coverName ? data.coverAlt : undefined],
        ["toc", data.toc],
        ["legacyUrls", data.legacyUrls.length ? data.legacyUrls : undefined],
      ],
      GENERATED_HEADER,
    );

    const files = new Map<string, Buffer>([["index.md", Buffer.from(`${frontmatter}\n\n${transformed.body}`, "utf8")]]);
    for (const [abs, name] of transformed.assets) files.set(name, readFileSync(abs));

    // Compare with what's on disk.
    let status: PlannedArticle["status"] = "create";
    const changed: string[] = [];
    const removed: string[] = [];
    if (existing) {
      const onDisk = (await readdir(existing.dir, { withFileTypes: true })).filter((e) => e.isFile()).map((e) => e.name);
      for (const [name, content] of files) {
        let current: Buffer | undefined;
        try {
          current = await readFile(join(existing.dir, name));
        } catch {
          current = undefined;
        }
        if (!current || !current.equals(content)) changed.push(name);
      }
      for (const name of onDisk) if (!files.has(name)) removed.push(name);
      status = changed.length || removed.length || renamedFrom ? "update" : "unchanged";
    }
    plan.articles.push({ slug: data.slug, source: note.rel, status, files, changed, removed, renamedFrom });
  }

  // Imported articles whose note is no longer publishable.
  const plannedSlugs = new Set(plan.articles.map((a) => a.slug));
  const reservedByCandidates = new Set(candidates.map((n) => n.data!.slug));
  for (const article of site.values()) {
    if (article.managed && !plannedSlugs.has(article.slug) && !reservedByCandidates.has(article.slug)) {
      plan.stale.push({ slug: article.slug, source: article.importedFrom! });
    }
  }

  plan.articles.sort((a, b) => a.slug.localeCompare(b.slug));
  plan.stale.sort((a, b) => a.slug.localeCompare(b.slug));
  return plan;
}

export async function applyPlan(plan: ImportPlan, options: { prune: boolean; pruneConfirmed: boolean }): Promise<ApplyResult> {
  if (plan.errors.length) throw new Error("Refusing to write: the import plan has errors.");
  if (options.prune && !options.pruneConfirmed) throw new Error("Refusing to prune without confirmation.");
  const contentDir = resolve(plan.contentDir);
  const result: ApplyResult = { written: [], pruned: [] };

  for (const article of plan.articles) {
    if (article.status === "unchanged") continue;
    if (!SLUG_PATTERN.test(article.slug)) throw new Error(`Unsafe slug: ${article.slug}`);
    const dir = join(contentDir, article.slug);
    await mkdir(dir, { recursive: true });
    const toWrite = article.status === "create" ? [...article.files.keys()] : article.changed;
    for (const name of toWrite) {
      if (name.includes("/") || name.startsWith(".")) throw new Error(`Unsafe file name: ${name}`);
      await writeFile(join(dir, name), article.files.get(name)!);
    }
    for (const name of article.removed) await rm(join(dir, name), { force: true });
    result.written.push(article.slug);
  }

  if (options.prune) {
    const site = await readSite(contentDir);
    for (const stale of plan.stale) {
      const article = site.get(stale.slug);
      // Re-check at delete time: only importer-managed folders are ever removed.
      if (!article?.managed || !SLUG_PATTERN.test(stale.slug)) continue;
      await rm(article.dir, { recursive: true, force: true });
      result.pruned.push(stale.slug);
    }
  }
  return result;
}
