type Files = Record<string, string | Buffer>;

async function setup(vaultFiles: Files, siteFiles: Files = {}) {
  const root = await mkdtemp(join(tmpdir(), "ninjatronics-import-test-"));
  const vaultDir = join(root, "vault");
  const contentDir = join(root, "site", "src", "content", "blog");
  await mkdir(join(vaultDir, "articles"), { recursive: true });
  await mkdir(contentDir, { recursive: true });
  for (const [path, content] of Object.entries(vaultFiles)) {
    await mkdir(dirname(join(vaultDir, path)), { recursive: true });
    await writeFile(join(vaultDir, path), content);
  }
  for (const [path, content] of Object.entries(siteFiles)) {
    await mkdir(dirname(join(contentDir, path)), { recursive: true });
    await writeFile(join(contentDir, path), content);
  }
  return { root, vaultDir, contentDir, cleanup: () => rm(root, { recursive: true, force: true }) };
}

function note(fields: Record<string, string>, body = "Body text.\n"): string {
  const base: Record<string, string> = {
    publish: "true",
    draft: "false",
    slug: "example",
    title: '"Example"',
    description: '"An example."',
    pubDate: "2025-01-15",
    category: "linux",
  };
  const merged = { ...base, ...fields };
  const lines = Object.entries(merged)
    .filter(([, v]) => v !== "__omit__")
    .map(([k, v]) => `${k}: ${v}`);
  return `---\n${lines.join("\n")}\n---\n\n${body}`;
}

const errorsMatch = (plan: ImportPlan, pattern: RegExp) =>
  assert.ok(plan.errors.some((e) => pattern.test(e)), `expected an error matching ${pattern}, got:\n${plan.errors.join("\n") || "(no errors)"}`);

